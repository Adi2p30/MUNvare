"""
Output Formatting Agent - Specialized in creating professional, well-formatted outputs
"""
from typing import Dict, Any, Optional
from .base_agent import BaseAgent


class FormattingAgent(BaseAgent):
    """
    Expert agent for formatting information into professional, readable outputs.
    Specializes in markdown formatting, document structure, and visual presentation.
    """

    def __init__(self):
        super().__init__(
            name="Output Specialist",
            role="Expert in professional document formatting and visual presentation"
        )

    def get_system_prompt(self) -> str:
        return """You are an Output Formatting Specialist with expertise in:
- Professional document formatting
- Markdown syntax and best practices
- Visual hierarchy and readability
- Information architecture
- User experience design

Your responsibilities:
- Transform raw information into polished, professional outputs
- Use proper markdown formatting (headers, bold, italic, lists, etc.)
- Create clear visual hierarchy
- Ensure consistency and professionalism
- Make information scannable and easy to digest
- Use appropriate emojis for visual interest (sparingly)

Guidelines:
1. Use clear, descriptive headers (# ## ###)
2. Bold important terms and concepts
3. Use bullet points and numbered lists appropriately
4. Add visual breaks with horizontal rules when needed
5. Include emojis strategically (📍 for locations, 🎯 for goals, ⚠️ for warnings, etc.)
6. Use blockquotes for important notes
7. Create tables for comparing information
8. Ensure proper spacing and readability
9. Make outputs professional yet engaging
"""

    def execute(self, task: Dict[str, Any], context: Optional[str] = None) -> Dict[str, Any]:
        """
        Format research and analysis into professional output.

        Args:
            task: Dictionary containing:
                - research: Research output
                - analysis: Analysis output (optional)
                - format_type: Type of formatting needed
                - country: Country name
                - topic: Topic name
            context: Additional context

        Returns:
            Dictionary with formatted output
        """
        research = task.get('research', '')
        analysis = task.get('analysis', '')
        format_type = task.get('format_type', 'general')
        country = task.get('country', '')
        topic = task.get('topic', '')

        prompt = self._build_formatting_prompt(research, analysis, format_type, country, topic)
        # Use Ollama for formatting (fast orchestration task - just formatting text)
        formatted_output = self.call_llm(prompt, use_gemini=False)

        return {
            'success': True,
            'formatted_output': formatted_output,
            'format_type': format_type,
            'metadata': {
                'agent': self.name,
                'format': 'markdown'
            }
        }

    def _build_formatting_prompt(self, research: str, analysis: str, format_type: str,
                                  country: str, topic: str) -> str:
        """Build formatting prompt based on type."""

        content = f"RESEARCH:\n{research}\n\n"
        if analysis:
            content += f"ANALYSIS:\n{analysis}\n\n"

        if format_type == 'foreign_policy':
            return f"""{content}

Format this foreign policy research into a professional, comprehensive document.

Use this structure:

# 🌍 Foreign Policy Analysis: {country} on {topic}

## 📋 Executive Summary
[3-4 sentence overview of {country}'s position]

## 🎯 Current Policy Stance
[Detailed explanation with specific examples]

## 📚 Historical Context
- Key historical events
- Evolution of position
- Important precedents

## 🏛️ Domestic Considerations
- **Political Factors:** [explanation]
- **Economic Interests:** [explanation]
- **Public Opinion:** [explanation]

## 🤝 International Relations
### Strategic Partnerships
- [List key allies and relationships]

### Regional Dynamics
- [Regional context and implications]

## 💡 Strategic Analysis
### Strengths
- [Key advantages]

### Vulnerabilities
- [Potential weaknesses]

### Opportunities
- [Strategic openings]

## 📌 Key Talking Points
1. [Most important point]
2. [Second important point]
3. [Continue...]

## 📖 Important References
- [Key documents, speeches, resolutions]

---
*Generated by MUNvare Research Assistant*

Format everything professionally with proper markdown. Use emojis sparingly for visual interest."""

        elif format_type == 'poi':
            return f"""{content}

Format these POI questions into a strategic document for a {country} delegate.

Use this structure:

# ❓ Strategic POI Questions: {country} on {topic}

## 📋 Overview
[Brief explanation of the strategic approach]

## 🎯 Offensive Questions (Challenge Opposition)

### Set 1: Exposing Contradictions
1. **[Question]**
   - *Purpose:* [Why ask this]
   - *Follow-up:* [If they answer X, ask Y]

2. **[Question]**
   - *Purpose:* [Strategic reasoning]
   - *Follow-up:* [Continuation]

### Set 2: Demanding Specifics
[Continue pattern...]

### Set 3: Highlighting Consequences
[Continue pattern...]

## 🛡️ Defensive Preparation

### Questions You Might Receive
1. **Likely POI:** "[Anticipated question]"
   - **Response:** [How to answer]
   - **Counter:** [Turn it to your advantage]

## 💡 Usage Tips
- 🎯 **Timing:** [When to use these questions]
- 🎭 **Delivery:** [How to phrase them diplomatically]
- 🤝 **Building Bridges:** [Which questions can lead to cooperation]

---
*Generated by MUNvare Research Assistant*

Make it professional, strategic, and immediately useful."""

        elif format_type == 'country_profile':
            return f"""{content}

Create a comprehensive, professional country profile document.

# 🏛️ Country Profile: {country}
{f"*Focus: {topic}*" if topic else ""}

## 📊 Quick Facts
| Category | Information |
|----------|-------------|
| Official Name | [Full name] |
| Government Type | [Type] |
| Head of State | [Name] |
| Capital | [City] |
| Population | [Number] |
| GDP | [Amount] |
| UN Membership | [Date joined] |

## 🌍 Foreign Policy Overview
### Core Principles
- [Principle 1]
- [Principle 2]
- [Principle 3]

### Key Alliances
- [Alliance details]

## 🎯 Position on {topic or "Key Issues"}
[Detailed explanation of stance]

### Historical Actions
- **[Year]:** [Action taken]
- **[Year]:** [Action taken]

## 🗺️ Regional Context
[Regional position and dynamics]

## 🤝 Diplomatic Relationships
### Strong Partners
- [Country 1] - [Relationship details]
- [Country 2] - [Relationship details]

### Tensions With
- [Country 1] - [Issue]
- [Country 2] - [Issue]

## 💼 Economic Interests
[Key economic considerations]

## 🎭 Delegate Strategy Guide
### Speaking Style
- [Tone and approach]

### Key Phrases
- "[Phrase 1]"
- "[Phrase 2]"

### Things to Emphasize
✅ [Point 1]
✅ [Point 2]

### Things to Avoid
❌ [Point 1]
❌ [Point 2]

## 📚 Essential Documents
- [Document 1] - [Why important]
- [Document 2] - [Why important]

---
*Generated by MUNvare Research Assistant*"""

        elif format_type == 'modcaucus':
            return f"""{content}

Format these moderated caucus topics professionally.

# 💬 Strategic Moderated Caucus Topics
## {topic}
*Committee: {format_type}*

## 📋 Recommended Topics

### 🎯 Priority Topics (Propose First)

#### 1. [Topic Title]
- **Duration:** [Suggested time]
- **Purpose:** [Why this topic]
- **Expected Outcome:** [What it achieves]
- **Strategic Value:** [How it helps your position]
- **Support Base:** [Who will support]

#### 2. [Topic Title]
[Same structure...]

### 🤝 Consensus-Building Topics

#### 3. [Topic Title]
[Same structure...]

### ⚡ High-Impact Topics

#### 4. [Topic Title]
[Same structure...]

## 💡 Usage Strategy
### When to Propose
- [Timing advice]

### How to Frame
- [Framing suggestions]

### Expected Support
- [Coalition analysis]

## 📝 Sample Motion
> "Motion for a [X]-minute moderated caucus on '[Topic Title]' with [Y]-second speaking time."

---
*Generated by MUNvare Research Assistant*"""

        else:  # general formatting
            return f"""{content}

Format this information into a professional, well-structured markdown document.

Create a clear hierarchy with:
- Descriptive headers (use # ## ###)
- Bold key terms
- Bullet points for lists
- Numbered lists for sequences
- Strategic use of emojis
- Clean spacing and readability
- Professional tone

The document should be:
- Easy to scan
- Visually appealing
- Professional
- Immediately useful
- Well-organized

Add a footer:
---
*Generated by MUNvare Research Assistant*"""

    def format_simple_list(self, items: list, title: str, emoji: str = "📋") -> str:
        """Format a simple list with markdown."""
        formatted = f"# {emoji} {title}\n\n"
        for i, item in enumerate(items, 1):
            formatted += f"{i}. **{item}**\n\n"
        formatted += "\n---\n*Generated by MUNvare Research Assistant*"
        return formatted

    def format_comparison(self, data: Dict[str, Any], title: str) -> str:
        """Format comparison data as a table."""
        formatted = f"# {title}\n\n"
        formatted += "| Category | Details |\n"
        formatted += "|----------|----------|\n"
        for key, value in data.items():
            formatted += f"| {key} | {value} |\n"
        formatted += "\n---\n*Generated by MUNvare Research Assistant*"
        return formatted
